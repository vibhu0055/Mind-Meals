// computeWhoStatus — main entry point
// Returns { zscore, who_category, age_months } or null if insufficient data
// =============================================================
export const computeWhoStatus = (bmi, gender, dateOfBirth, measurementDate, ageYears) => {
  if (!bmi) return null;

  let ageMonths = computeAgeMonths(dateOfBirth, measurementDate);

  // Fallback: use integer age (middle of year)
  if (ageMonths === null && ageYears) {
    ageMonths = ageYears * 12 + 6;
  }

  if (!ageMonths || ageMonths < 61 || ageMonths > 228) {
    // Outside WHO reference range (under 5 or over 19)
    return { zscore: null, who_category: null, age_months_at_measurement: ageMonths };
  }

  const g      = (gender || 'male').toLowerCase() === 'female' ? 'female' : 'male';
  const zscore = computeZScore(parseFloat(bmi), g, ageMonths);
  const who_category = getWhoCategory(zscore);

  return { zscore, who_category, age_months_at_measurement: ageMonths };
};


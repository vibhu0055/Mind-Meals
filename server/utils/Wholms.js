// Build lookup maps: age_months → { L, M, S }
const buildLookup = (data) => {
  const map = {};
  for (const [month, L, M, S] of data) map[month] = { L, M, S };
  return map;
};

const LMS_LOOKUP = {
  male:   buildLookup(LMS_BOYS),
  female: buildLookup(LMS_GIRLS),
};

// =============================================================
// getLMS — get L, M, S for a given gender and age in months.
// Clamps to 61–228. Linear interpolation for fractional months.
// =============================================================
const getLMS = (gender, ageMonths) => {
  const table = LMS_LOOKUP[gender] || LMS_LOOKUP.male;
  const clamped = Math.max(61, Math.min(228, Math.round(ageMonths)));
  return table[clamped] || table[61];
};

// =============================================================
// computeZScore — WHO LMS z-score formula with extreme adjustment
// =============================================================
export const computeZScore = (bmi, gender, ageMonths) => {
  const { L, M, S } = getLMS(gender, ageMonths);

  // Core LMS formula
  let z = (Math.pow(bmi / M, L) - 1) / (S * L);

  // Adjustment for extreme values (|z| > 3)
  if (Math.abs(z) > 3) {
    // Compute SD2 and SD3 on the appropriate side
    const sign = z > 0 ? 1 : -1;
    const SD3  = M * Math.pow(1 + L * S * (sign * 3), 1 / L);
    const SD2  = M * Math.pow(1 + L * S * (sign * 2), 1 / L);
    const SD23 = Math.abs(SD3 - SD2);
    z = sign * 3 + (bmi - SD3) / SD23;
  }

  return Math.round(z * 1000) / 1000; // 3 decimal places
};

// =============================================================
// getWhoCategory — maps z-score to our 5 categories
//
//   ≤ -3          → severe_thinness
//   -3 < z ≤ -2   → thinness
//   -2 < z ≤ -1   → moderate_risk   (lower normal — our split)
//   -1 < z ≤ +2   → normal          (WHO normal + overweight folded in)
//   z > +2        → obese
// =============================================================
export const getWhoCategory = (zscore) => {
  if (zscore <= -3)  return 'severe_thinness';
  if (zscore <= -2)  return 'thinness';
  if (zscore <= -1)  return 'moderate_risk';
  if (zscore <= 2)   return 'normal';
  return 'obese';
};

// =============================================================
// computeAgeMonths — exact age in months from DOB + measurement date
// Falls back to years * 12 + 6 if DOB not available
// =============================================================
export const computeAgeMonths = (dateOfBirth, measurementDate) => {
  if (!dateOfBirth) return null;

  const dob  = new Date(dateOfBirth);
  const meas = measurementDate ? new Date(measurementDate) : new Date();

  const years  = meas.getFullYear() - dob.getFullYear();
  const months = meas.getMonth() - dob.getMonth();
  const days   = meas.getDate() - dob.getDate();

  let totalMonths = years * 12 + months;
  if (days < 0) totalMonths -= 1; // haven't completed this month yet

  return Math.max(0, totalMonths);
};

